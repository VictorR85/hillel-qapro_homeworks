// ДЗ 7.1 — Сума вартості послуг

// объект с услугами — ключ это название, значение это цена строкой
var services = {
    "стрижка":      "60 грн",
    "гоління":      "80 грн",
    "Миття голови": "100 грн"
};

// добавляем новую услугу по ходу — так работает объект в JS
services['Розбити скло'] = "200 грн";


// ============================================
// Метод 1: price() — считает СУММУ всех услуг
// ============================================
services.price = function() {

    // накопитель суммы — начинаем с нуля
    let total = 0;

    // перебираем все свойства объекта services
    for (let key in services) {

        // пропускаем методы — берём только строки с ценами
        // typeof проверяет тип: если строка — это цена, если function — пропускаем
        if (typeof services[key] === 'string') {

            // parseInt вытаскивает число из строки "60 грн" → 60
            total += parseInt(services[key]);
        }
    }

    // возвращаем итоговую сумму
    return total;
};


// ============================================
// Метод 2: minPrice() — находит МИНИМАЛЬНУЮ цену
// ============================================
services.minPrice = function() {

    // начинаем с бесконечности — любая реальная цена будет меньше
    let min = Infinity;
    let minName = '';  // название самой дешёвой услуги

    for (let key in services) {

        // пропускаем методы — только строки с ценами
        if (typeof services[key] === 'string') {

            // вытаскиваем число из строки
            let price = parseInt(services[key]);

            // если эта цена меньше текущего минимума — запоминаем
            if (price < min) {
                min = price;
                minName = key;  // запоминаем название услуги
            }
        }
    }

    // возвращаем результат
    return minName + ': ' + min + ' грн';
};


// ============================================
// Метод 3: maxPrice() — находит МАКСИМАЛЬНУЮ цену
// ============================================
services.maxPrice = function() {

    // начинаем с нуля — любая реальная цена будет больше
    let max = 0;
    let maxName = '';  // название самой дорогой услуги

    for (let key in services) {

        // пропускаем методы — только строки с ценами
        if (typeof services[key] === 'string') {

            // вытаскиваем число из строки
            let price = parseInt(services[key]);

            // если эта цена больше текущего максимума — запоминаем
            if (price > max) {
                max = price;
                maxName = key;  // запоминаем название услуги
            }
        }
    }

    // возвращаем результат
    return maxName + ': ' + max + ' грн';
};


// ============================================
// Проверяем все три метода:
// ============================================
console.log('Загальна вартість: ' + services.price()    + ' грн');
console.log('Мінімальна ціна: '   + services.minPrice());
console.log('Максимальна ціна: '  + services.maxPrice());