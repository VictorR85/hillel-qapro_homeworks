// ===========================
// 1) 'number' + 3 + 3
// ===========================
// JS читает слева направо =>
// сначала видит строку 'number' и число 3
// строка слева + 3: 'number3'
// потом 'number3' + 3: 'number33'
'number' + 3 + 3;


// ===========================
// 2) null + 3
// ===========================
// null — это "пусто", но JS считает его как 0
// 0 + 3 = 3
// Результат: 3
null + 3;


// ===========================
// 3) 5 && "qwerty"
// ===========================
// && проверяет значения слева направо
// 5 — это не ноль и не пусто, значит идём дальше
// "qwerty" — последнее значение, оба прошли проверку, возвращаем последнее
// Результат:
5 && "qwerty";


// ===========================
// 4) +'40' + +'2' + "hillel"
// ===========================
// + перед одним значением (не между двумя) — это => число
// +'40' превращается в число 40
// +'2' превращается в число 2
// 40 + 2 = 42
// 42 + "hillel" — число и строка = '42hillel'
+'40' + +'2' + "hillel";


// ===========================
// 5) '10' - 5 === 6
// ===========================
// - умеет только вычитать, поэтому "10" = 10
// 10 - 5 = 5
// 5 === 6 — строгое сравнение, тип и значение, 5 не равно 6
// Результат: false
'10' - 5 === 6;


// ===========================
// 6) true + false
// ===========================
// JS превращает булевы значения в числа при математике
// true = 1, false = 0
// 1 + 0 = 1
// Результат: 1
true + false;


// 7) '4px' - 3
// минус пытается сделать из '4px' число
// но строка содержит буквы px — перевести в число не получается
// получаем NaN (Not a Number — "это не число")
// любое действие с NaN даёт снова NaN
// Результат: NaN
'4px' - 3;


// 8) '4' - 3
// минус превращает '4' в число 4 — тут всё хорошо, только цифра
// 4 - 3 = 1
// Результат: 1
'4' - 3;


// 9) '6' + 3 ** 0
// ** — это степень, у него самый высокий приоритет среди арифметики
// поэтому сначала считаем 3 ** 0 = 1 (любое число в степени 0 это 1)
// потом '6' + 1 — слева строка, значит клеим: '61'
// Результат: '61'
'6' + 3 ** 0;


// 10) 12 / '6'
// деление всегда работает с числами
// '6' превращается в число 6
// 12 / 6 = 2
// Результат: 2
12 / '6';


// 11) '10' + (5 === 6)
// скобки считаются первыми
// 5 === 6 — строгое сравнение, 5 не равно 6, получаем false
// '10' + false — строка и что-то ещё — JS клеит, false становится 'false'
// Результат: '10false'
'10' + (5 === 6);


// 12) null == ''
// тут нестрогое сравнение ==
// но null по правилам JS равен только null или undefined — и всё
// пустая строка '' под это не подходит
// Результат: false
null == '';


// 13) 3 ** (9 / 3)
// скобки считаются первыми: 9 / 3 = 3
// потом 3 ** 3 = 27 (3 умножить на себя 3 раза: 3*3*3)
// Результат: 27
3 ** (9 / 3);

// 14) !!'false' == !!'true'
// ! меняет значение на противоположное (true/false)
// !! — два восклицательных — это просто узнать: ложь или правда?
// 'false' — строка с буквами, НЕ пустая — значит правда → !!'false' = true
// 'true' — тоже строка, тоже НЕ пустая — тоже правда → !!'true' = true
// true == true — одинаковые значения
// Результат: true
!!'false' == !!'true';

// 15) 0 || '0' && 1
// && проверяется раньше чем || — такой приоритет
// '0' — строка с символом, не пустая — значит правда
// '0' && 1 — оба истинные, возвращаем последнее: 1
// 0 || 1 — 0 это ложь, смотрим дальше, 1 это правда — возвращаем 1
// Результат: 1
0 || '0' && 1;

// 16) (+null == false) < 1
// сначала скобки
// +null — это 0 (null в математике = 0)
// 0 == false — false при сравнении тоже становится 0, значит 0 == 0, это true
// true < 1 — true это 1, значит 1 < 1 — нет, не меньше
// Результат: false
(+null == false) < 1;

// 17) false && true || true
// && считается раньше ||
// false && true — левый ложный, сразу стоп, возвращаем false
// false || true — false ложный, берём правый: true
// Результат: true
false && true || true;

// 18) false && (false || true)
// && видит слева false — это ложь
// не смотрим что там в скобках вообще, сразу возвращаем false
// это называется "короткое замыкание" — зачем считать дальше если уже ясно
// Результат: false
false && (false || true);

// 19) (+null == false) < 1 ** 5
// ** считается первым: 1 ** 5 = 1 (единица в любой степени это 1)
// скобки: +null = 0, 0 == false это true (как в примере 16)
// true < 1 — true это 1, значит 1 < 1 — нет
// Результат: false
(+null == false) < 1 ** 5;
