// ДЗ 5.1 — Функция pow(x, y)
// Задание: написать функцию, которая возводит число в степень
// Условие: нельзя использовать оператор ** (только то, что проходили)

// Функцию pow + 2 числа:
// x — это число, которое возвести в степень
// y — это сама степень (сколько раз умножать x на себя)
function pow(x, y) {

    // Создаем переменную result
    // Начинаем с 1, потому что умножение на 1 ничего не меняет
    // Если бы начали с 0 — результат всегда был бы 0, это неверно
    let result = 1;

    // Запускаем цикл, который повторится "y" раз
    for (let i = 0; i < y; i++) {

        // * result на "x"
        result = result * x;
    }

    // Возвращаем итоговый результат
    return result;
}

// Проверяем работу функции pow на примерах:

console.log(pow(2, 3));  // ожидаем 8    → 2 умножить на себя 3 раза: 2*2*2
console.log(pow(3, 3));  // ожидаем 27   → 3 умножить на себя 3 раза: 3*3*3
console.log(pow(5, 2));  // ожидаем 25   → 5 умножить на себя 2 раза: 5*5
console.log(pow(10, 4)); // ожидаем 10000 → 10*10*10*10
console.log(pow(7, 1));  // ожидаем 7    → цикл сработает 1 раз: 1*7 = 7